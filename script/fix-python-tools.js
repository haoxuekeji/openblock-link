/**
 * Repair the portable Python toolchain after extraction (P2-3).
 *
 * Windows layout (tools/Python/Scripts) problems fixed here:
 *
 * 1. pip-generated console wrappers such as Scripts/esptool.py import a
 *    module carrying the same name as the wrapper file. openblock-link runs
 *    them as `python Scripts/esptool.py`, which puts Scripts/ in front of
 *    sys.path, so `import esptool` resolves to the wrapper itself
 *    (self-shadowing) and dies with `AttributeError: ... no attribute
 *    '_main'`. Deleting the wrapper is not an option because link spawns it
 *    by that exact path, so instead a "shadow guard" is injected that drops
 *    the script's own folder from sys.path before the real import runs.
 *
 * 2. Scripts/obmpy (extensionless file, exactly what link spawns through
 *    python) can be missing from the packaged toolchain. Generate it, plus
 *    an obmpy.cmd for humans running from cmd.exe.
 *
 * POSIX layouts (tools/Python/bin) ship working wrappers and are left alone.
 */
const fs = require('fs');
const path = require('path');

const GUARD_MARKER = 'openblock-link fix-python-tools shadow guard';

const SHADOW_GUARD = [
    `# --- ${GUARD_MARKER} (do not remove) ---`,
    '# Keep this script\'s own folder off sys.path so that imports resolve to',
    '# the real site-packages modules instead of same-named wrapper scripts.',
    'import os as _ob_os',
    'import sys as _ob_sys',
    '_ob_here = _ob_os.path.dirname(_ob_os.path.abspath(__file__))',
    '_ob_sys.path[:] = [',
    '    _ob_p for _ob_p in _ob_sys.path',
    '    if _ob_os.path.abspath(_ob_p if _ob_p else _ob_os.getcwd()) != _ob_here',
    ']',
    'del _ob_os, _ob_sys, _ob_here',
    '# --- end shadow guard ---'
].join('\n');

const hasShadowGuard = source => String(source || '').includes(GUARD_MARKER);

/**
 * A wrapper needs the guard when it imports a module named after its own
 * file (pip console-script pattern). Full standalone scripts (e.g. the
 * esptool 3.3 single-file build shipped in POSIX layouts) never import
 * themselves and are skipped.
 * @param {string} source - script contents.
 * @param {string} moduleName - script basename without the .py suffix.
 * @return {boolean} true when the guard should be injected.
 */
const needsShadowGuard = (source, moduleName) => {
    if (hasShadowGuard(source)) {
        return false;
    }
    const escaped = String(moduleName).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const selfImport = new RegExp(`^\\s*(?:import|from)\\s+${escaped}\\b`, 'm');
    return selfImport.test(String(source || ''));
};

/**
 * Insert the shadow guard after the shebang / coding-comment header so it
 * runs before the wrapper's first real import.
 * @param {string} source - original script contents.
 * @return {string} patched script contents.
 */
const injectShadowGuard = source => {
    const lines = String(source || '').split('\n');
    let insertAt = 0;
    while (insertAt < lines.length) {
        const line = lines[insertAt].trim();
        if (line === '' || line.startsWith('#')) {
            insertAt += 1;
        } else {
            break;
        }
    }
    lines.splice(insertAt, 0, SHADOW_GUARD);
    return lines.join('\n');
};

// Same console entry point as the POSIX bin/obmpy wrapper pip generates,
// hardened with the shadow guard and a portable shebang.
const buildObmpyWrapper = () => [
    '#!/usr/bin/env python3',
    '# -*- coding: utf-8 -*-',
    '# Generated by openblock-link fix-python-tools: console wrapper for obmpy.',
    SHADOW_GUARD,
    'import re',
    'import sys',
    '',
    'from obmpy.__init__ import _main',
    '',
    "if __name__ == '__main__':",
    "    sys.argv[0] = re.sub(r'(-script\\.pyw?|\\.exe)?$', '', sys.argv[0])",
    '    sys.exit(_main())',
    ''
].join('\n');

// cmd.exe convenience wrapper; python.exe sits one level above Scripts.
const buildObmpyCmd = () => [
    '@echo off',
    '"%~dp0..\\python.exe" "%~dp0obmpy" %*',
    ''
].join('\r\n');

/**
 * Fix a portable Python directory in place. No-op for POSIX layouts.
 * @param {string} pythonDir - e.g. <link>/tools/Python.
 * @return {Array.<string>} repo-relative names of the files patched/created.
 */
const fixPythonTools = pythonDir => {
    const changed = [];
    const scriptsDir = path.join(pythonDir, 'Scripts');
    if (!fs.existsSync(scriptsDir)) {
        return changed;
    }

    fs.readdirSync(scriptsDir).forEach(name => {
        if (!name.endsWith('.py')) {
            return;
        }
        const filePath = path.join(scriptsDir, name);
        if (!fs.statSync(filePath).isFile()) {
            return;
        }
        const source = fs.readFileSync(filePath, 'utf8');
        const moduleName = name.slice(0, -3);
        if (!needsShadowGuard(source, moduleName)) {
            return;
        }
        fs.writeFileSync(filePath, injectShadowGuard(source));
        changed.push(`Scripts/${name}`);
    });

    const obmpyPath = path.join(scriptsDir, 'obmpy');
    if (!fs.existsSync(obmpyPath)) {
        fs.writeFileSync(obmpyPath, buildObmpyWrapper());
        changed.push('Scripts/obmpy');
    }

    const obmpyCmdPath = path.join(scriptsDir, 'obmpy.cmd');
    if (!fs.existsSync(obmpyCmdPath)) {
        fs.writeFileSync(obmpyCmdPath, buildObmpyCmd());
        changed.push('Scripts/obmpy.cmd');
    }

    return changed;
};

if (require.main === module) {
    const pythonDir = process.argv[2] || path.join(__dirname, '../tools/Python');
    const changed = fixPythonTools(pythonDir);
    if (changed.length === 0) {
        console.log(`fix-python-tools: nothing to patch in ${pythonDir}`);
    } else {
        console.log(`fix-python-tools: patched ${changed.join(', ')}`);
    }
}

module.exports = {
    fixPythonTools,
    needsShadowGuard,
    injectShadowGuard,
    hasShadowGuard,
    buildObmpyWrapper,
    buildObmpyCmd
};
